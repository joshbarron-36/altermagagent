"""Write N seeded synthetic CrSe project trees with a ground-truth JSON next to each, for the accuracy test."""

import json
import os
import random
import shutil
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_demo import A_POS, A_REL, C_POS, C_REL, outcar, oszicar, poscar, vf  # noqa: E402

HOUR, DAY = 3600, 86400
STRAIN = (1.03, 0.985)  # biaxial strain of a and c for the second structure
NAMES = {
    "relax": ["01_relax", "relax", "1-relax", "opt"],
    "old_try": ["old_try", "relax_old", "test"],
    "scf": ["scf", "02_scf", "2-scf", "static"],
    "scf_U": ["scf_U{u}", "U{u}", "scf_U{u}_new"],
    "bands": ["bands_path", "bands", "03_bands", "band"],
    "soc": ["soc", "scf_soc", "04_soc"],
    "soc_bands": ["soc_bands", "bands_soc", "soc/bands"],
    "wannier": ["wan90", "wannier", "05_wannier"],
    "test": ["test", "test_encut", "tmp"],
}
BASE_INCAR = "SYSTEM = CrSe {what}\nISPIN = 2\nENCUT = {encut}\nISMEAR = 0\nSIGMA = 0.05\nEDIFF = 1E-6\n"


# Pick a folder name for a role that is not used yet in this tree.
def pick_name(rng, role, used, prefix, **fmt):
    pool = [n.format(**fmt) for n in NAMES[role]]
    rng.shuffle(pool)
    for n in pool:
        full = prefix + n
        if full not in used:
            used.add(full)
            return full
    n = f"{prefix}{pool[0]}_{len(used)}"
    used.add(n)
    return n


# Write the INCAR text of one run from its settings.
def incar_text(rng, r):
    t = BASE_INCAR.format(what=r["role"], encut=r.get("encut", 500))
    mag = "0 0 3 0 0 -3 0 0 0 0 0 0" if r["soc"] else rng.choice(["3 -3 0 0", "3 -3 2*0", "1*3 1*-3 2*0"])
    t += f"MAGMOM = {mag}\n"
    if r["soc"]:
        t += rng.choice(["LSORBIT = .TRUE.\n", "LSORBIT = T\n"]) + "SAXIS = 0 0 1\nISYM = 0\n"
    if r["u"] is not None:
        t += f"LDAU = .TRUE.\nLDAUTYPE = 2\nLDAUL = 2 -1\nLDAUU = {r['u']:.1f} 0.0\nLDAUJ = 0.0 0.0\n"
    phase = r["phase"]
    if phase == "relax":
        t += f"IBRION = {rng.choice([1, 2])}\nNSW = {rng.choice([40, 60, 100])}\nISIF = 3\nEDIFFG = -0.01\n"
    elif phase == "scf":
        t += rng.choice(["NSW = 0\nIBRION = -1\n", "NSW = 0\nIBRION = 2   ! copied from relax, NSW = 0 makes it static\n", ""])
        t += "LCHARG = .TRUE.\nLWAVE = .TRUE.\n"
    elif phase == "band":
        t += rng.choice(["ICHARG = 11\n", "ICHARG=11   # read CHGCAR\n", "icharg = 11 ; LORBIT = 11\n"]) + "NSW = 0\nNBANDS = 16\n"
    elif phase == "wannier":
        t += "ISTART = 1\nNSW = 0\nNBANDS = 48\nNUM_WANN = 22\n" + rng.choice(["LWANNIER90 = .TRUE.\n", "LWANNIER90 = T\n"])
    return t


# Return the vasprun.xml text: closed when the run finished, cut off otherwise.
def vasprun_text(done):
    head = '<?xml version="1.0" encoding="ISO-8859-1"?>\n<modeling>\n <generator>\n  <i name="program" type="string">vasp </i>\n </generator>\n'
    return head + (" <calculation>\n </calculation>\n</modeling>\n" if done else " <calculation>\n  <scstep>\n")


# Write the files of one run and set their times; returns nothing, never touches other runs.
def write_run(root, r, runs_by_name, now):
    d = root / r["name"]
    d.mkdir(parents=True, exist_ok=True)
    a, c = (A_REL * STRAIN[0], C_REL * STRAIN[1]) if r["struct"] == 1 else (A_REL, C_REL)
    t0, t1 = r["start"], r["end"]
    inputs, outputs = {}, {}
    inputs["INCAR"] = incar_text(r["rng"], r)
    if r["phase"] == "band":
        inputs["KPOINTS"] = r["rng"].choice([
            "Line mode G-M-K-G-A\n60\nLine-mode\nReciprocal\n 0.0 0.0 0.0 ! G\n 0.5 0.0 0.0 ! M\n",
            "K-Path Generated by VASPKIT.\n   20\nLine-Mode\nReciprocal\n   0.000   0.000   0.000     GAMMA\n   0.500   0.000   0.000     M\n",
            "kpath\n40\nline\nrec\n0 0 0 G\n0.5 0 0 M\n"])
    else:
        inputs["KPOINTS"] = "Automatic mesh\n0\nGamma\n 12 12 8\n 0 0 0\n"
    start_pos = r["role"] == "old_try" or (r["role"] == "relax" and r["true_parent"] is None)
    inputs["POSCAR"] = poscar(A_POS, C_POS) if start_pos else poscar(a, c)
    inputs["POTCAR"] = " PAW_PBE Cr 06Sep2000\n PAW_PBE Se 06Sep2000\n"
    copied = {}
    if r.get("copy"):
        src = runs_by_name[r["true_parent"]]
        copied[r["copy"]] = src["end"] if r.get("cp_p") else t0
    out = r["out"]
    energy = -36.9 - 0.14 * r["soc"] - 0.3 * (r["u"] or 0) + r["rng"].uniform(-0.01, 0.01)
    kind = {"completed": "ok", "error": "err", "running": "run"}.get(r["status"])
    if out != "inputs_only":
        if out in ("outcar", "outcar_cut"):
            text = outcar("relax" if r["phase"] == "relax" else r["name"], kind or "run", energy, r["soc"])
            if out == "outcar_cut":
                text = text.split(" General timing")[0]
            outputs["OUTCAR"] = text
        outputs["OSZICAR"] = oszicar(kind or "run", energy, r["soc"])
        log = [" running on   32 total cores", " vasp.6.4.2 20Jul23 (build Aug 10 2026 14:02:11) complex",
               " POSCAR found :  2 types and       4 ions"]
        if r["status"] == "error":
            log += (["   1 F= " + vf(energy), " ZBRENT: fatal error in bracketing",
                     "     please rerun with smaller EDIFF, or copy CONTCAR", "     to POSCAR and continue"]
                    if r["error"] == "ZBRENT" else
                    ["DAV:   3    -0.369E+02   -0.12E+01   -0.33E+00  4096   0.11E+01",
                     " Error EDDDAV: Call to ZHEGV failed. Returncode =   7 1  16"])
        elif r["status"] == "completed":
            log += ["   1 F= " + vf(energy), " writing wavefunctions"]
        else:
            log += [" entering main loop", "DAV:  12    -0.370405E+02   -0.17E-03   -0.31E-02  8064   0.19E-01"]
        outputs[r["log"]] = "\n".join(log) + "\n"
        if r["status"] == "completed" or r["status"] == "error":
            outputs["CONTCAR"] = poscar(a, c)
        if r["vasprun"]:
            outputs["vasprun.xml"] = vasprun_text(r["status"] == "completed")
        for big in r.get("writes", []):
            outputs[big] = "placeholder, reference only\n"
        if r["phase"] == "wannier" and r["status"] == "completed":
            outputs["wannier90.wout"] = " All done: wannier90 exiting\n"
            outputs["wannier90_hr.dat"] = " written on 14Sep2026\n          22\n"
    if r["phase"] == "wannier":
        inputs["wannier90.win"] = "num_wann = 22\nnum_bands = 48\nwrite_hr = .true.\n"
    for files, stamp in ((inputs, t0), (outputs, t1)):
        for n, text in files.items():
            (d / n).write_text(text)
            os.utime(d / n, (stamp, stamp))
    for n, stamp in copied.items():
        (d / n).write_text("placeholder copied from the parent run\n")
        os.utime(d / n, (stamp, stamp))


# Decide the expected parent label from the story, using only facts a careful reader can see in the files.
def expected_parent(r, earlier):
    same = [e for e in earlier if e["struct"] == r["struct"] and e["phase"] != "band"]
    need = {"chg": "CHGCAR", "wav": "WAVECAR"}.get(r.get("tag"))
    if need:
        pool = [e for e in same if need in e["kept"] and e["soc"] == r["soc"] and e["u"] == r["u"]]
    else:
        pool = same
    names = [e["name"] for e in pool]
    if r["true_parent"] is None or not pool:
        return {"label": "unknown", "true_parent": r["true_parent"], "candidates": []}
    if len(pool) == 1:
        return {"label": names[0], "true_parent": r["true_parent"], "candidates": names}
    return {"label": "candidates", "true_parent": r["true_parent"], "candidates": names}


# Build the story of one tree: which runs exist, their settings, times, status and true parent.
def story(seed, now):
    rng = random.Random(seed)
    used, runs = set(), []
    clock = [now - rng.uniform(30, 60) * DAY]

    # Append one run to the story with its settings and the next slot on the clock.
    def add(role, phase, struct, prefix, parent=None, tag=None, soc=False, u=None, status="completed", **kw):
        name = pick_name(rng, role, used, prefix, u=int(u) if u else 0)
        clock[0] += rng.uniform(2 * HOUR, 3 * DAY)
        start = clock[0]
        end = start + rng.uniform(0.3 * HOUR, 6 * HOUR)
        clock[0] = end
        r = {"name": name, "role": role, "phase": phase, "struct": struct, "true_parent": parent, "tag": tag,
             "soc": soc, "u": u, "status": status, "start": start, "end": end, "rng": random.Random(rng.random()),
             "vasprun": rng.random() < 0.6, "log": rng.choice(["vasp.log", "vasp.out", f"slurm-{rng.randint(10000, 99999)}.out"]),
             "out": "outcar", "writes": [], "error": None}
        r.update(kw)
        if status == "error":
            r["error"] = r["error"] or ("ZBRENT" if phase == "relax" else rng.choice(["ZBRENT", "EDDDAV"]))
            r["out"] = "outcar_cut"
        elif status == "missing":
            r["out"] = rng.choice(["inputs_only", "outcar_cut"])
        elif status == "completed" and rng.random() < 0.1:
            r["out"], r["vasprun"] = "no_outcar", True
        if phase in ("scf", "relax") and status == "completed":
            r["writes"] = ["CHGCAR", "WAVECAR"] if phase == "scf" else rng.choice([[], ["CHGCAR"], ["CHGCAR", "WAVECAR"]])
        if tag in ("chg", "wav"):
            r["copy"] = "CHGCAR" if tag == "chg" else "WAVECAR"
            r["cp_p"] = rng.random() < 0.5
        runs.append(r)
        return r

    for struct in ([0, 1] if rng.random() < 0.5 else [0]):
        prefix = "" if struct == 0 else rng.choice(["strain_3pct/", "strained/", "a+3%/"])
        if struct == 0:
            old = add("old_try", "relax", 0, prefix, status="error", error="ZBRENT") if rng.random() < 0.4 else None
            # After a ZBRENT stop the usual habit is to copy CONTCAR to POSCAR and relax again, with no restart tag.
            relax = add("relax", "relax", 0, prefix, parent=old["name"] if old else None)
            top = relax["name"]
        else:
            top = None  # the strained cell is written by hand, so its first run has no parent in the files
        scf = add("scf", "scf", struct, prefix, parent=top)
        if top is None:
            top = scf["name"]  # later strained runs copy their POSCAR from the first strained run
        sources = [scf]
        for u in rng.sample([3.0, 4.0, 5.0], k=rng.choice([0, 0, 1, 2])):
            sources.append(add("scf_U", "scf", struct, prefix, parent=top, u=u))
        if rng.random() < 0.3:
            add("test", "scf", struct, prefix, parent=top, encut=300, status=rng.choice(["completed", "error", "missing"]))
        if rng.random() < 0.85:
            src = rng.choice(sources)
            add("bands", "band", struct, prefix, parent=src["name"], tag="chg", u=src["u"],
                status=rng.choice(["completed"] * 4 + ["error", "missing"]))
        if struct == 0 and rng.random() < 0.7:
            soc = add("soc", "scf", 0, prefix, parent=top, soc=True)
            if rng.random() < 0.6:
                add("soc_bands", "band", 0, prefix, parent=soc["name"], tag="chg", soc=True,
                    status=rng.choice(["completed"] * 3 + ["error"]))
            if rng.random() < 0.6:
                add("wannier", "wannier", 0, prefix, parent=soc["name"], tag="wav", soc=True,
                    status=rng.choice(["completed"] * 3 + ["error"]))
    # Some cleanup after the fact: a few CHGCAR or WAVECAR files deleted to save disk.
    for r in runs:
        r["kept"] = [w for w in r["writes"] if rng.random() > 0.15]
    # The last run may still be going: recent times, no completion marker.
    if rng.random() < 0.4 and runs[-1]["phase"] != "relax":
        last = runs[-1]
        last["status"], last["out"], last["error"] = "running", "outcar_cut", None
        last["start"], last["end"] = now - rng.uniform(1.5, 3) * HOUR, now - rng.uniform(3, 20) * 60
        last["writes"], last["kept"] = [], []
    return runs


# Write one tree and its truth JSON; returns the truth dictionary.
def make_tree(root, seed, now=None):
    now = now or time.time()
    root = Path(root)
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)
    runs = story(seed, now)
    by_name = {r["name"]: r for r in runs}
    truth = {"seed": seed, "tree": root.name, "runs": {}}
    for i, r in enumerate(runs):
        saved = r["writes"]
        r["writes"] = r["kept"]
        write_run(root, r, by_name, now)
        r["writes"] = saved
        truth["runs"][r["name"]] = {
            "phase": r["phase"], "status": r["status"], "parent": expected_parent(r, runs[:i]),
            "role": r["role"], "structure": ["CrSe", "CrSe strained"][r["struct"]], "soc": r["soc"], "U": r["u"],
            "restart": {"chg": "ICHARG=11", "wav": "ISTART=1"}.get(r["tag"], "none (file time only)"),
            "files_deleted": sorted(set(r["writes"]) - set(r["kept"]))}
    (root.parent / f"{root.name}.truth.json").write_text(json.dumps(truth, indent=1))
    return truth


# Command line: write N trees under an output folder, seeds 1 to N.
def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="Write N synthetic CrSe trees with ground-truth JSON files.")
    ap.add_argument("--n", type=int, default=20)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent / "variants"))
    ap.add_argument("--seed", type=int, default=1, help="first seed; tree k uses seed + k")
    args = ap.parse_args(argv)
    out = Path(args.out)
    for k in range(args.n):
        t = make_tree(out / f"tree_{k + 1:02d}", args.seed + k)
        print(f"{out / t['tree']}: {len(t['runs'])} runs")


if __name__ == "__main__":
    sys.exit(main())
